// Sets up the web app's demo wallet: a second, testnet-only key that lets visitors without a wallet
// watch a real payment. It is separate from the deployer on purpose: the deployer owns the contracts,
// and its key should never sit on a web host.
//   npm run demo:wallet        create the key if needed (in .env, never printed) and top it up
import { appendFileSync, existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { formatEther, formatUnits, parseEther, parseUnits } from 'viem'
import { generatePrivateKey, privateKeyToAccount } from 'viem/accounts'
import { ERC20_ABI, ROOT, account, network, publicClient, txOverrides, walletClient } from './lib.mjs'

const CHAINS = (process.env.DEMO_CHAINS || 'baseSepolia,unichainSepolia').split(',')
const ETH_TARGET = parseEther('0.0003') // a demo payment costs a tiny fraction of this in gas
const USDC_TARGET = parseUnits('5', 6) // each demo moves 0.10, and it comes straight back

const envPath = join(ROOT, process.env.DEPLOYMENT === 'local' ? 'devnet.env' : '.env')
let key = process.env.DEMO_PRIVATE_KEY
if (!key) {
  const existing = existsSync(envPath) ? readFileSync(envPath, 'utf8') : ''
  key = generatePrivateKey()
  appendFileSync(envPath, `${existing.endsWith('\n') || !existing ? '' : '\n'}# Testnet-only demo wallet for the web app, generated by scripts/demo-wallet.mjs.\nDEMO_PRIVATE_KEY=${key}\n`)
  console.log(`Created a demo wallet key in ${process.env.DEPLOYMENT === 'local' ? 'devnet.env' : '.env'}.`)
}
const demo = privateKeyToAccount(key.startsWith('0x') ? key : `0x${key}`).address
console.log(`Demo wallet: ${demo}\nFunded from the deployer ${account().address}\n`)

for (const chainKey of CHAINS) {
  const n = network(chainKey)
  const client = publicClient(chainKey)
  const wallet = walletClient(chainKey)

  const eth = await client.getBalance({ address: demo })
  if (eth < ETH_TARGET / 2n) {
    const hash = await wallet.sendTransaction({ to: demo, value: ETH_TARGET - eth, ...(await txOverrides(chainKey)) })
    await client.waitForTransactionReceipt({ hash })
  }
  const usdc = await client.readContract({ address: n.usdc, abi: ERC20_ABI, functionName: 'balanceOf', args: [demo] })
  if (usdc < USDC_TARGET / 5n) {
    const hash = await wallet.writeContract({ address: n.usdc, abi: ERC20_ABI, functionName: 'transfer', args: [demo, USDC_TARGET - usdc] })
    await client.waitForTransactionReceipt({ hash })
  }

  const [ethNow, usdcNow] = await Promise.all([
    client.getBalance({ address: demo, blockTag: 'latest' }),
    client.readContract({ address: n.usdc, abi: ERC20_ABI, functionName: 'balanceOf', args: [demo] }),
  ])
  console.log(`${n.name.padEnd(18)} ${formatEther(ethNow).slice(0, 10).padStart(10)} ETH   ${formatUnits(usdcNow, 6).padStart(8)} USDC`)
}
console.log('\nFor hosting, set DEMO_PRIVATE_KEY from .env as a secret environment variable. Never commit it.')
