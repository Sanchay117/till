// Creates a fresh, testnet-only deployer key in .env (if there isn't one) and prints its ADDRESS.
// The private key is never printed. Do not reuse a key that holds real funds.
//   npm run wallet
import { appendFileSync, existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { generatePrivateKey, privateKeyToAccount } from 'viem/accounts'
import { ROOT } from './lib.mjs'

const envPath = join(ROOT, '.env')
const existing = existsSync(envPath) ? readFileSync(envPath, 'utf8') : ''
const match = existing.match(/^DEPLOYER_PRIVATE_KEY=(0x)?([0-9a-fA-F]{64})\s*$/m)

let address
if (match) {
  address = privateKeyToAccount(`0x${match[2]}`).address
  console.log('A deployer key already exists in .env.')
} else {
  const key = generatePrivateKey()
  address = privateKeyToAccount(key).address
  const prefix = existing && !existing.endsWith('\n') ? '\n' : ''
  appendFileSync(envPath, `${prefix}# Testnet-only deployer key, generated by scripts/wallet.mjs. Never commit this file.\nDEPLOYER_PRIVATE_KEY=${key}\n`)
  console.log('Created a new testnet-only deployer key in .env (git-ignored).')
}

console.log(`\nDeployer address: ${address}\n`)
console.log('Fund this address with testnet coins, then run `npm run balances`:')
console.log('  - Base Sepolia ETH      about 0.06  (0.05 of it becomes 5 lREACT, see below)')
console.log('  - Unichain Sepolia ETH  about 0.002')
console.log('  - Ethereum Sepolia ETH  about 0.002 (optional third pay chain)')
console.log('  - Test USDC on each pay chain from https://faucet.circle.com')
console.log('  - lREACT: `npm run faucet` swaps Base Sepolia ETH for lREACT at 1 ETH = 100 lREACT')
