// Bundles the demo wallet's handler (server/handler.ts) into one self-contained file a serverless
// host can run as is: api/demo/[action].js. The bundle is committed.
//   npm run build:api
//
// Why bundle instead of letting the host compile the TypeScript: hosts compile each function file
// on its own and leave its imports alone. That breaks on this project's extensionless imports, on
// the JSON import of the deployment, and on files outside /api. One file with no imports cannot
// break that way.
import { build } from 'esbuild'
import { statSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outfile = join(root, 'api', 'demo', '[action].js')

await build({
  entryPoints: [join(root, 'server', 'handler.ts')],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  minify: true,
  legalComments: 'none',
  banner: {
    js: [
      '// GENERATED by scripts/build-api.mjs from server/handler.ts and server/demo.ts. Do not edit.',
      '// Run `npm run build:api` after changing those files or redeploying the contracts.',
      // Some bundled dependencies still call require() for Node built-ins.
      "import { createRequire as __createRequire } from 'node:module';",
      'const require = __createRequire(import.meta.url);',
    ].join('\n'),
  },
})

console.log(`api/demo/[action].js  ${(statSync(outfile).size / 1024).toFixed(0)} KB`)
